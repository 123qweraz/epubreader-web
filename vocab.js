/* ---------- 分析: 返回 { rows, stats } ----------
   range: {type:'all'} | {type:'chapter',index} | {type:'unit',unit}
   生词 = 出现次数≥minCount 且不在常用词表的二字对, 按次数降序 */
async function vocabAnalyze(range = { type: "all" }, minCount = 2) {
  const book = state.book;
  if (!book) return { rows: [], stats: null };
  const key = `v:${range.type}:${range.chapter ?? range.unit ?? ""}:${minCount}`;
  if (book.vocabCache && book.vocabCache.get && book.vocabCache.get(key)) return book.vocabCache.get(key);
  const chapters = vocabRangeChapters(range);
  const bigramMap = new Map();
  let totalHan = 0, totalPairs = 0;
  for (const i of chapters) {
    let text;
    try { text = await chapterText(i); } catch { text = ""; }
    totalHan += vocabHanCount(text);
    let run = "";
    const commitRun = () => {
      for (let k = 0; k + 1 < run.length; k++) {
        const bg = run.slice(k, k + 2);
        const rec = bigramMap.get(bg) || { count: 0, chapter: i, off: -1 };
        rec.count++;
        if (rec.off < 0) rec.off = text.indexOf(bg);
        bigramMap.set(bg, rec);
        totalPairs++;
      }
      run = "";
    };
    for (const ch of text) { if (VOCAB_HAN.test(ch)) run += ch; else commitRun(); }
    commitRun();
  }
  const rows = [];
  for (const [word, rec] of bigramMap) {
    if (VOCAB_COMMON_BIGRAMS.has(word)) continue;
    if (rec.count < minCount) continue;
    rows.push({ word, count: rec.count, chapter: rec.chapter, off: rec.off });
  }
  rows.sort((a, b) => b.count - a.count || a.word.localeCompare(b.word, "zh"));
  const stats = {
    totalHan,
    totalPairs,
    uniquePairs: bigramMap.size,
    newWords: rows.length
  };
  const result = { rows, stats };
  (book.vocabCache = book.vocabCache || new Map()).set(key, result);
  return result;
}

/* 统计一段文本中的汉字数(与遍历同口径) */
function vocabHanCount(text) {
  let n = 0;
  for (const ch of text) if (VOCAB_HAN.test(ch)) n++;
  return n;
}

/* 解析范围内的章节索引列表 */
function vocabRangeChapters(range) {
  const book = state.book;
  const n = book.spine.length;
  if (range.type === "chapter") return [Math.max(0, Math.min(range.chapter, n - 1))];
  if (range.type === "unit") {
    const u = state.navUnits[range.unit];
    return u != null ? [Math.max(0, Math.min(u.i, n - 1))] : [state.chapterIndex];
  }
  const arr = [];
  for (let i = 0; i < n; i++) arr.push(i);
  return arr;
}

/* 渲染生词表到面板容器 + 顶部统计卡片 */
async function vocabRender() {
  const container = $("vocabContent");
  const range = vocabCurrentRange();
  $("vocabStatus").textContent = t("vocabAnalyzing");
  container.innerHTML = "";
  const data = await vocabAnalyze(range);
  if (!data || !data.stats) { $("vocabStatus").textContent = t("vocabNoBook"); return; }
  $("vocabStatus").textContent = "";
  const stats = data.stats;
  const cardWrap = document.createElement("div");
  cardWrap.className = "vocabCards";
  const cards = [
    [t("vocabTotalChars"), stats.totalHan],
    [t("vocabPairs"), stats.totalPairs],
    [t("vocabUniquePairs"), stats.uniquePairs],
    [t("vocabNewWords"), stats.newWords]
  ];
  for (const [label, val] of cards) {
    const c = document.createElement("div");
    c.className = "vocabCard";
    const n = document.createElement("div"); n.className = "vocabCardNum"; n.textContent = val;
    const l = document.createElement("div"); l.className = "vocabCardLabel"; l.textContent = label;
    c.append(n, l);
    cardWrap.appendChild(c);
  }
  container.appendChild(cardWrap);
  if (!data.rows.length) {
    const e = document.createElement("div");
    e.className = "vocabEmpty";
    e.textContent = t("vocabEmpty");
    container.appendChild(e);
    return;
  }
  const list = document.createElement("div");
  list.className = "vocabList";
  for (const r of data.rows) {
    const row = document.createElement("button");
    row.className = "vocabRow";
    const w = document.createElement("span"); w.className = "vocabWord"; w.textContent = r.word;
    const cnt = document.createElement("span"); cnt.className = "vocabCount"; cnt.textContent = r.count;
    const chap = document.createElement("span"); chap.className = "vocabChapter"; chap.textContent = vocabChapterLabel(r.chapter);
    row.append(w, cnt, chap);
    row.onclick = () => { safeShow(r.chapter, "", { highlightTerm: r.word, highlightOffset: r.off }); switchSideTab("toc"); };
    list.appendChild(row);
  }
  container.appendChild(list);
}

/* 章节显示名: 优先 toc 标签, 退化到 "第N章" */
function vocabChapterLabel(i) {
  const e = state.tocEntries && state.tocEntries.find(x => x.chapterIndex === i);
  if (e && e.label) return e.label;
  return t("chapterN", i + 1);
}

/* 当前选中的范围(由面板单选决定) */
function vocabCurrentRange() {
  const sel = $("vocabRangeSelect");
  const mode = sel ? sel.value : "all";
  if (mode === "chapter") return { type: "chapter", chapter: state.chapterIndex };
  if (mode === "unit") return { type: "unit", unit: state.unitIdx };
  return { type: "all" };
}

function vocabClear() {
  if (state.book) state.book.vocabCache = null;
}
